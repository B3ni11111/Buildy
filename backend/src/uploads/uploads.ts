import { BadRequestException } from '@nestjs/common';
import { randomUUID } from 'node:crypto';
import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';

/** The subset of multer's file object we use (memory storage). */
export interface UploadedFileData {
  originalname: string;
  mimetype: string;
  size: number;
  buffer: Buffer;
}

export const MAX_UPLOAD_BYTES = 10 * 1024 * 1024;
/** How long a presigned download link works. */
export const PRESIGN_SECONDS = 5 * 60;

/** File types building documents and issue attachments may have. */
export const ALLOWED_MIME_TYPES = new Set([
  'application/pdf',
  'image/png',
  'image/jpeg',
  'image/webp',
  'image/gif',
  'text/plain',
  'application/msword',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  'application/vnd.ms-excel',
  'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  'application/vnd.ms-powerpoint',
  'application/vnd.openxmlformats-officedocument.presentationml.presentation',
]);

export function assertAllowedFile(file: UploadedFileData) {
  if (!ALLOWED_MIME_TYPES.has(file.mimetype)) throw new BadRequestException('This file type is not supported');
}

let client: S3Client | undefined;
function s3() {
  // Credentials come from AWS_ACCESS_KEY_ID / AWS_SECRET_ACCESS_KEY in the environment.
  client ??= new S3Client({ region: process.env.AWS_REGION ?? 'us-east-1' });
  return client;
}

function bucket() {
  const name = process.env.S3_BUCKET;
  if (!name) throw new Error('S3_BUCKET is not set');
  return name;
}

/** Lowercase `[a-z0-9._-]` only, truncated (keeping the extension). */
export function safeFilename(name: string) {
  const cleaned = name
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, '-')
    .replace(/-{2,}/g, '-')
    .replace(/^[-.]+|[-]+$/g, '');
  if (!cleaned) return 'file';
  const dot = cleaned.lastIndexOf('.');
  const ext = dot > 0 ? cleaned.slice(dot).slice(0, 10) : '';
  const base = (dot > 0 ? cleaned.slice(0, dot) : cleaned).slice(0, 60);
  return `${base}${ext}` || 'file';
}

/** `buildings/<id>/images|documents/<uuid>-<name>` — images by mime type, everything else is a document. */
export function buildingKey(buildingId: string, file: Pick<UploadedFileData, 'originalname' | 'mimetype'>) {
  const folder = file.mimetype.startsWith('image/') ? 'images' : 'documents';
  return `buildings/${buildingId}/${folder}/${randomUUID()}-${safeFilename(file.originalname)}`;
}

/** `users/<id>/avatars/<uuid>-<name>` */
export function avatarKey(userId: string, originalname: string) {
  return `users/${userId}/avatars/${randomUUID()}-${safeFilename(originalname)}`;
}

/** Uploads to the private bucket under a key. The key is generated by us — never from client input. */
export async function putObject(key: string, file: UploadedFileData) {
  await s3().send(
    new PutObjectCommand({ Bucket: bucket(), Key: key, Body: file.buffer, ContentType: file.mimetype }),
  );
  return key;
}

/** Allow-list check, then upload under a building key. Returns the key. */
export async function saveUpload(buildingId: string, file: UploadedFileData) {
  assertAllowedFile(file);
  return putObject(buildingKey(buildingId, file), file);
}

/** Deletes stored files key by key; failures (e.g. already gone) are ignored. */
export async function removeUploads(keys: string[]) {
  await Promise.all(
    keys.map((Key) =>
      s3()
        .send(new DeleteObjectCommand({ Bucket: bucket(), Key }))
        .catch(() => undefined),
    ),
  );
}

/** A link to read one object for 5 minutes. Call only after the access checks have passed. */
export async function presignGet(key: string, mimeType: string) {
  const url = await getSignedUrl(
    s3(),
    new GetObjectCommand({ Bucket: bucket(), Key: key, ResponseContentType: mimeType }),
    { expiresIn: PRESIGN_SECONDS },
  );
  return { url };
}
